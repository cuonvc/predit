/**
 * Unified .ass Subtitle Compiler (assCompiler.ts)
 * Compiles all visible textTracks (ai_caption_en, ai_caption_vi, manual_text)
 * into a single UTF-8 .ass file for single-pass FFmpeg libass burn-in.
 */

import { TextTrack, TextStylePreset } from "../store/useTimelineStore";

/**
 * Converts standard #RRGGBB hex and opacity (0.0 - 1.0) into ASS &HAABBGGRR format.
 * Note: In ASS format, Alpha 00 is opaque and FF is transparent.
 */
export function hexToAssColor(hex: string, opacity = 1.0): string {
  const clean = hex.replace("#", "").trim();
  const r = clean.substring(0, 2) || "FF";
  const g = clean.substring(2, 4) || "FF";
  const b = clean.substring(4, 6) || "FF";

  const clampedOpacity = Math.max(0, Math.min(1, opacity));
  const assAlpha = Math.round((1 - clampedOpacity) * 255)
    .toString(16)
    .toUpperCase()
    .padStart(2, "0");

  return `&H${assAlpha}${b.toUpperCase()}${g.toUpperCase()}${r.toUpperCase()}`;
}

/**
 * Formats seconds float (e.g., 12.4) to ASS timestamp H:MM:SS.cc (e.g., 0:00:12.40)
 */
export function secondsToAssTime(sec: number): string {
  const totalSec = Math.max(0, sec);
  const hours = Math.floor(totalSec / 3600);
  const minutes = Math.floor((totalSec % 3600) / 60);
  const seconds = Math.floor(totalSec % 60);
  const centiseconds = Math.round((totalSec - Math.floor(totalSec)) * 100);

  return `${hours}:${String(minutes).padStart(2, "0")}:${String(
    seconds
  ).padStart(2, "0")}.${String(Math.min(99, centiseconds)).padStart(2, "0")}`;
}

export function compileUnifiedAssFile(
  textTracks: TextTrack[],
  resolution: { width: number; height: number }
): string {
  const visibleTracks = textTracks.filter((t) => t.visible);

  const header = [
    "[Script Info]",
    "Title: Generated by Predit Video Editor",
    "ScriptType: v4.00+",
    `PlayResX: ${resolution.width}`,
    `PlayResY: ${resolution.height}`,
    "WrapStyle: 2",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, OutlineColour, BackColour, Bold, BorderStyle, Outline, Shadow, Alignment, MarginV",
  ];

  const styleLines: string[] = [];
  const dialogueLines: string[] = [];

  visibleTracks.forEach((track, trackIdx) => {
    const preset: TextStylePreset = track.stylePreset;
    const primaryColor = hexToAssColor(preset.color, 1.0);
    const outlineColor = hexToAssColor(preset.strokeColor, 1.0);
    const backColor = preset.backgroundBox.enabled
      ? hexToAssColor(preset.backgroundBox.color, preset.backgroundBox.opacity)
      : "&HFF000000";
    const borderStyle = preset.backgroundBox.enabled ? 3 : 1;

    styleLines.push(
      `Style: ${track.id},${preset.fontFamily},${preset.fontSize},${primaryColor},${outlineColor},${backColor},-1,${borderStyle},${preset.strokeWidth},0,5,0`
    );

    const layer = track.role === "manual_text" ? 2 : 1 + (trackIdx % 2);

    for (const clip of track.clips) {
      const effectivePos = clip.overrideStyle?.position || preset.position;
      const posX = Math.round(effectivePos.x * resolution.width);
      const posY = Math.round(effectivePos.y * resolution.height);

      const overrideTags: string[] = [`\\pos(${posX},${posY})`];
      if (clip.overrideStyle?.color) {
        overrideTags.push(
          `\\c${hexToAssColor(clip.overrideStyle.color, 1.0)}&`
        );
      }
      if (clip.overrideStyle?.fontSize) {
        overrideTags.push(`\\fs${clip.overrideStyle.fontSize}`);
      }

      const startAss = secondsToAssTime(clip.startTime);
      const endAss = secondsToAssTime(clip.endTime);
      const sanitizedText = clip.text.replace(/\r?\n/g, "\\N");

      dialogueLines.push(
        `Dialogue: ${layer},${startAss},${endAss},${track.id},,0,0,0,,{${overrideTags.join(
          ""
        )}}${sanitizedText}`
      );
    }
  });

  return [
    ...header,
    ...styleLines,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ...dialogueLines,
    "",
  ].join("\n");
}
