use editor_core::helpers::compute_effective_text_style;
use editor_core::models::{Resolution, TextAlign, TextTrack, TextTrackRole, VerticalAlign};

/// Converts standard `#RRGGBB` hex and opacity (0.0 - 1.0) into ASS `&HAABBGGRR` format.
pub fn hex_to_ass_color(hex: &str, opacity: f64) -> String {
    let clean = hex.trim().trim_start_matches('#');
    let r = clean.get(0..2).unwrap_or("FF").to_uppercase();
    let g = clean.get(2..4).unwrap_or("FF").to_uppercase();
    let b = clean.get(4..6).unwrap_or("FF").to_uppercase();

    let clamped = opacity.clamp(0.0, 1.0);
    let ass_alpha = ((1.0 - clamped) * 255.0).round() as u8;
    format!("&H{ass_alpha:02X}{b}{g}{r}")
}

/// Formats seconds float (e.g. `12.4`) to ASS timestamp `H:MM:SS.cc` (`0:00:12.40`).
pub fn seconds_to_ass_time(sec: f64) -> String {
    let total = sec.max(0.0);
    let hours = (total / 3600.0).floor() as u32;
    let minutes = ((total % 3600.0) / 60.0).floor() as u32;
    let seconds = (total % 60.0).floor() as u32;
    let centiseconds = (((total - total.floor()) * 100.0).round() as u32).min(99);
    format!("{hours}:{minutes:02}:{seconds:02}.{centiseconds:02}")
}

pub fn compile_unified_ass_file(text_tracks: &[TextTrack], resolution: Resolution) -> String {
    let mut lines = vec![
        "[Script Info]".to_string(),
        "Title: Generated by Predit Video Editor".to_string(),
        "ScriptType: v4.00+".to_string(),
        format!("PlayResX: {}", resolution.width),
        format!("PlayResY: {}", resolution.height),
        "WrapStyle: 2".to_string(),
        "ScaledBorderAndShadow: yes".to_string(),
        String::new(),
        "[V4+ Styles]".to_string(),
        "Format: Name, Fontname, Fontsize, PrimaryColour, OutlineColour, BackColour, Bold, BorderStyle, Outline, Shadow, Alignment, MarginV".to_string(),
    ];

    let mut dialogue_lines = Vec::new();

    for (idx, track) in text_tracks.iter().filter(|t| t.visible).enumerate() {
        let preset = &track.style_preset;
        let primary_color = hex_to_ass_color(&preset.color, 1.0);
        let outline_color = hex_to_ass_color(&preset.stroke_color, 1.0);
        let back_color = if preset.background_box.enabled {
            hex_to_ass_color(&preset.background_box.color, preset.background_box.opacity)
        } else {
            "&HFF000000".to_string()
        };
        let border_style = if preset.background_box.enabled { 3 } else { 1 };
        let font_family = if preset.font_family.is_empty() || preset.font_family == "System Default"
        {
            "Segoe UI"
        } else {
            &preset.font_family
        };

        lines.push(format!(
            "Style: {},{},{},{},{},{},-1,{},{},0,5,0",
            track.id,
            font_family,
            preset.font_size as u32,
            primary_color,
            outline_color,
            back_color,
            border_style,
            preset.stroke_width as u32
        ));

        let layer = if track.role == TextTrackRole::ManualText {
            2
        } else {
            1 + (idx % 2)
        };

        for clip in &track.clips {
            let eff = compute_effective_text_style(preset, clip.override_style.as_ref(), None);
            let pos_x = (eff.position.x * resolution.width as f64).round() as i32;
            let pos_y = (eff.position.y * resolution.height as f64).round() as i32;

            let mut tags = vec![format!("\\pos({pos_x},{pos_y})")];
            if eff.color != preset.color {
                tags.push(format!("\\c{}&", hex_to_ass_color(&eff.color, 1.0)));
            }
            if (eff.font_size - preset.font_size).abs() > 0.1 {
                tags.push(format!("\\fs{}", eff.font_size as u32));
            }
            if eff.bold {
                tags.push("\\b1".into());
            }
            if eff.italic {
                tags.push("\\i1".into());
            }
            if eff.underline {
                tags.push("\\u1".into());
            }

            let ass_align = match (eff.vertical_align, eff.text_align) {
                (VerticalAlign::Top, TextAlign::Left) => 7,
                (VerticalAlign::Top, TextAlign::Center) => 8,
                (VerticalAlign::Top, TextAlign::Right) => 9,
                (VerticalAlign::Bottom, TextAlign::Left) => 1,
                (VerticalAlign::Bottom, TextAlign::Center) => 2,
                (VerticalAlign::Bottom, TextAlign::Right) => 3,
                (VerticalAlign::Middle, TextAlign::Left) => 4,
                (VerticalAlign::Middle, TextAlign::Center) => 5,
                (VerticalAlign::Middle, TextAlign::Right) => 6,
            };
            tags.push(format!("\\an{ass_align}"));

            let start_ass = seconds_to_ass_time(clip.start_time);
            let end_ass = seconds_to_ass_time(clip.end_time);
            let sanitized = clip.text.replace("\r\n", "\\N").replace('\n', "\\N");

            dialogue_lines.push(format!(
                "Dialogue: {layer},{start_ass},{end_ass},{},,0,0,0,,{{{}}}{sanitized}",
                track.id,
                tags.join("")
            ));
        }
    }

    lines.push(String::new());
    lines.push("[Events]".to_string());
    lines.push(
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
            .to_string(),
    );
    lines.extend(dialogue_lines);
    lines.push(String::new());
    lines.join("\n")
}

